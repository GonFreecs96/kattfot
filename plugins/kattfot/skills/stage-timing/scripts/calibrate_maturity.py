#!/usr/bin/env python3
"""calibrate_maturity.py — measure a spine's settle curves and propose lags.

The funnel spec's `stage_maturity` block is the one place this template ships
an assumption wearing a measurement's clothes: hand-authored lag days, flagged
`illustrative: true / calibrated_at: null`, with a promise that "in a real
deployment this block is GENERATED by measuring open-anchored settle time on
the spine." This script is that generator.

For every ladder stage with a measurable arrival timestamp it computes the
**empirical settle curve** — the distribution of
`TIMESTAMP_DIFF(stage_ts, open_anchor_ts, DAY)` over cohorts old enough to
have fully settled — and reports:

  - the pooled p95 / p99 / p99.9 settle lags (nearest-rank, exact);
  - per-cohort p95 spread, so an unstable curve is visible rather than
    averaged away;
  - the share of events arriving later than the spec's *current* lag — the
    systematic bias a too-short lag injects into every "mature" rate; and
  - a proposed `stage_maturity` block, with `basis`, `percentile`,
    `calibrated_at`, and the calibration window recorded in machine-readable
    form. `--write` rewrites the block between the spec's
    `# >>> stage_maturity >>>` / `# <<< stage_maturity <<<` markers.

Why the tail matters this much: the only preregistered real-time comparison
of nowcasting methods (Wolffram et al. 2023, PLOS Comp Bio) found that
mis-specified maximum delays — professional teams choosing ~40 days when the
data kept revising past 80 — were the single biggest driver of systematic
bias, ahead of model choice. A maturity gate is exactly a maximum-delay
assumption, so it is the field's measured top failure mode; measuring it is
the point of this script.

Two honest limits, stated rather than discovered:

  - **Right-truncation guard, not a truncation-corrected estimator.** Events
    are only counted from cohorts at least `--min-cohort-age-days` old, so
    the delay distribution is read where it is (approximately) complete
    rather than corrected where it is not (Kalbfleisch & Lawless 1989 is the
    corrected version; this is the conservative one). If a measured tail
    percentile comes within a week of that age floor, the floor itself may be
    censoring the tail, and the output says so loudly.
  - **On fixtures, the calibration describes the generator.** The mechanism
    is identical, and running it against committed fixtures demonstrates it
    end to end — but the proposed block then keeps `illustrative: true` with
    `basis: open_anchored_days_fixture`, because a curve measured from a
    seeded random process must not dress itself as a measured business.

Stages with no arrival timestamp on the spine (the terminal-branch
pseudo-stages: a decline, a fraud fail, a staleness rule) cannot be measured
from settle curves; their current values are carried forward unchanged and
labeled as such in the proposal.

Output: JSON on stdout, same contract as the other spine skills.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from _shared import spine  # noqa: E402

MARKER_OPEN = "# >>> stage_maturity >>>"
MARKER_CLOSE = "# <<< stage_maturity <<<"

#: The pooled percentiles always reported (the proposal uses --percentile).
REPORT_PCTS = (95.0, 99.0, 99.9)


# ---------------------------------------------------------------------------
# Settle-column resolution
# ---------------------------------------------------------------------------


def settle_columns(spec: dict) -> tuple[str, dict[str, str]]:
    """(open_anchor_column, {maturity_stage: arrival_timestamp_column}).

    Derived from the spec rather than hardcoded: a transition's `to` column is
    the arrival timestamp for its `maturity_stage`, and a stage may also name
    its own `settle_column` directly (for ladder stages no transition arrives
    at). The open anchor is the first transition's `from` — the timestamp the
    whole ladder is anchored on.
    """
    transitions = spec.get("transitions") or []
    if not transitions:
        spine.refuse(
            f"the spec sourced from {spec.get('source_view', '?')} declares no "
            f"`transitions:`, so there is no open-anchor timestamp to measure "
            f"settle time against."
        )
    anchor = transitions[0]["from"]
    cols: dict[str, str] = {}
    for t in transitions:
        ms = t.get("maturity_stage")
        if ms:
            cols.setdefault(ms, t["to"])
    for s in spec.get("stages") or []:
        if s.get("settle_column"):
            cols.setdefault(s.get("maturity_stage", s["key"]), s["settle_column"])
    return anchor, cols


# ---------------------------------------------------------------------------
# Percentiles over a {lag_days: count} histogram (exact nearest-rank)
# ---------------------------------------------------------------------------


def nearest_rank(hist: dict[int, int], pct: float) -> int | None:
    """Exact nearest-rank percentile of a small integer histogram — the same
    basis stage-timing uses client-side, so a lag here and a percentile there
    are comparable numbers."""
    total = sum(hist.values())
    if not total:
        return None
    # ceil(pct/100 * total) computed WITHOUT truncating the product first: a
    # fractional percentile (99.9) times a total can exceed a multiple-of-100
    # boundary that int(pct*total) would drop below, yielding a rank one too
    # small and a tail percentile one bin too shallow — which, at p99.9, is
    # exactly the number the TRUNCATION RISK warning turns on.
    rank = max(1, math.ceil(pct * total / 100))
    cum = 0
    for lag in sorted(hist):
        cum += hist[lag]
        if cum >= rank:
            return lag
    return max(hist)


def tail_share(hist: dict[int, int], lag: int | None) -> float | None:
    """Share of events arriving strictly later than `lag` — the mass a
    maturity gate at that lag silently drops from every 'settled' rate."""
    total = sum(hist.values())
    if not total or lag is None:
        return None
    late = sum(n for d, n in hist.items() if d > lag)
    return late / total


# ---------------------------------------------------------------------------
# Measurement
# ---------------------------------------------------------------------------


def settle_sql(spec: dict, col: str, anchor: str, where: str, *, engine=None) -> str:
    """Delay histogram per cohort: one row per (cohort_week, lag_days).

    Grouped server-side so the result is O(cohorts x distinct lags), never one
    row per event — the whole curve for a stage comes back in a few hundred
    rows on either engine.
    """
    view = spine.fq_view(spec, engine=engine)
    cc = spec["cohort_column"]
    return (
        f"SELECT\n  {cc} AS cohort_week,\n"
        f"  TIMESTAMP_DIFF({col}, {anchor}, DAY) AS lag_days,\n"
        f"  COUNT(*) AS n\n"
        f"FROM `{view}`\n{where}\n"
        f"  AND {cc} <= @settled_through\n"
        f"  AND {col} IS NOT NULL\n"
        f"GROUP BY cohort_week, lag_days\nORDER BY cohort_week, lag_days"
    )


def measure_stage(rows: list[dict], pct: float, current_lag) -> dict:
    """Fold one stage's (cohort_week, lag_days, n) rows into the calibration
    read: pooled percentiles, per-cohort p95 spread, and the tail mass the
    current lag leaves behind."""
    pooled: dict[int, int] = {}
    by_cohort: dict[str, dict[int, int]] = {}
    negatives = 0
    for r in rows:
        lag, n = int(r["lag_days"]), int(r["n"])
        if lag < 0:
            negatives += n
            continue
        pooled[lag] = pooled.get(lag, 0) + n
        by_cohort.setdefault(str(r["cohort_week"]), {})[lag] = n
    cohort_p95 = [nearest_rank(h, 95.0) for h in by_cohort.values()]
    cohort_p95 = [p for p in cohort_p95 if p is not None]
    return {
        "events": sum(pooled.values()),
        "cohorts_used": len(by_cohort),
        "pooled": {f"p{str(p).rstrip('0').rstrip('.')}": nearest_rank(pooled, p) for p in REPORT_PCTS},
        "per_cohort_p95": {
            "min": min(cohort_p95) if cohort_p95 else None,
            "max": max(cohort_p95) if cohort_p95 else None,
        },
        "current_lag_days": current_lag,
        "tail_share_beyond_current_lag": tail_share(pooled, current_lag),
        "proposed_lag_days": nearest_rank(pooled, pct),
        "negative_lag_events": negatives,
    }


def measure_overrides(
    spec: dict, stage: str, cfg: dict, anchor: str, col: str,
    where: str, params: dict, pct: float, book_proposal: int | None, *, engine=None,
) -> dict:
    """Recalibrate one stage's per-group overrides: measure the settle curve
    per value of the override's `by` dimension, and propose an override only
    for values whose own p{pct} exceeds the book-wide proposal — the additive
    rule the spec documents (a group earns an override, it never inherits
    one)."""
    view = spine.fq_view(spec, engine=engine)
    cc = spec["cohort_column"]
    by = cfg["by"]
    dexpr = spine.col_expr(spec, by)
    sql = (
        f"SELECT\n  {dexpr} AS grp,\n"
        f"  TIMESTAMP_DIFF({col}, {anchor}, DAY) AS lag_days,\n"
        f"  COUNT(*) AS n\n"
        f"FROM `{view}`\n{where}\n"
        f"  AND {cc} <= @settled_through\n"
        f"  AND {col} IS NOT NULL\n"
        f"GROUP BY grp, lag_days\nORDER BY grp, lag_days"
    )
    rows = spine.run_query(spec["source_project"], sql, params, engine=engine)
    hists: dict[str, dict[int, int]] = {}
    for r in rows:
        lag = int(r["lag_days"])
        if lag < 0:
            continue
        hists.setdefault(str(r["grp"]), {})[lag] = (
            hists.setdefault(str(r["grp"]), {}).get(lag, 0) + int(r["n"])
        )
    measured = {g: nearest_rank(h, pct) for g, h in hists.items()}
    proposed = {
        g: lag
        for g, lag in measured.items()
        if lag is not None and book_proposal is not None and lag > book_proposal
    }
    return {"by": by, "measured": measured, "proposed": proposed, "sql": sql}


# ---------------------------------------------------------------------------
# Proposal assembly + spec rewrite
# ---------------------------------------------------------------------------


def build_proposal(
    spec: dict, results: dict, override_results: dict, *,
    pct: float, today: dt.date, start: dt.date, settled_through: dt.date,
    min_age: int, fixture: bool,
) -> dict:
    """The proposed stage_maturity block. Measured stages get their measured
    lag; keys the spine cannot measure carry the current value forward."""
    current = spine.stage_maturity_table(spec).get("lag_days") or {}
    lag_days: dict = {}
    carried: list[str] = []
    for key in current:
        m = results.get(key)
        if m and m.get("proposed_lag_days") is not None:
            lag_days[key] = m["proposed_lag_days"]
        else:
            lag_days[key] = current[key]
            carried.append(key)
    for key, m in results.items():  # measured stages absent from the old table
        if key not in lag_days and m.get("proposed_lag_days") is not None:
            lag_days[key] = m["proposed_lag_days"]

    overrides = {}
    for stage, o in override_results.items():
        if o["proposed"]:
            overrides[stage] = {"by": o["by"], "values": o["proposed"]}

    block: dict = {
        # On fixtures the flag stays true on purpose: the mechanism ran, the
        # numbers describe the generator. Only a warehouse-measured curve may
        # claim otherwise.
        "illustrative": bool(fixture),
        "basis": "open_anchored_days_fixture" if fixture else "open_anchored_days",
        "percentile": pct,
        "calibrated_at": today.isoformat(),
        "calibration_window": {
            "start": start.isoformat(),
            "settled_through": settled_through.isoformat(),
            "min_cohort_age_days": min_age,
        },
        "lag_days": lag_days,
    }
    if overrides:
        block["lag_days_overrides"] = overrides
    return block, carried


def render_block_yaml(block: dict, carried: list[str]) -> str:
    """The proposal as spec-ready YAML between the markers, with the carried-
    forward keys labeled — an unmeasurable lag must stay visibly hand-authored
    even inside a calibrated block."""
    lines = [MARKER_OPEN]
    lines.append("# Generated by stage-timing/scripts/calibrate_maturity.py — do not hand-edit")
    lines.append("# values; re-run the calibration instead.")
    lines.append("stage_maturity:")
    for k in ("illustrative", "basis", "percentile", "calibrated_at"):
        v = block[k]
        lines.append(f"  {k}: {json.dumps(v) if isinstance(v, str) else str(v).lower() if isinstance(v, bool) else v}")
    w = block["calibration_window"]
    lines.append("  calibration_window:")
    for k, v in w.items():
        lines.append(f"    {k}: {json.dumps(v) if isinstance(v, str) else v}")
    lines.append("  lag_days:")
    for k, v in block["lag_days"].items():
        suffix = "   # carried forward: no arrival timestamp on the spine (hand-authored)" if k in carried else ""
        lines.append(f"    {k}: {v}{suffix}")
    if block.get("lag_days_overrides"):
        lines.append("  lag_days_overrides:")
        for stage, cfg in block["lag_days_overrides"].items():
            lines.append(f"    {stage}:")
            lines.append(f"      by: {cfg['by']}")
            lines.append("      values:")
            for val, lag in cfg["values"].items():
                lines.append(f"        {val}: {lag}")
    lines.append(MARKER_CLOSE)
    return "\n".join(lines)


def write_spec(path: Path, rendered: str) -> None:
    """Replace the marker-delimited block in a spec file, refusing rather than
    guessing when the markers are absent or malformed."""
    text = path.read_text()
    i, j = text.find(MARKER_OPEN), text.find(MARKER_CLOSE)
    if i == -1 or j == -1 or j < i:
        spine.refuse(
            f"{path} has no intact '{MARKER_OPEN}' .. '{MARKER_CLOSE}' block to "
            f"rewrite — add the markers around stage_maturity first."
        )
    path.write_text(text[:i] + rendered + text[j + len(MARKER_CLOSE):])


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--module", default=None,
                    help=f"registry module (default: {spine.DEFAULT_MODULE})")
    ap.add_argument("--spine", default=None,
                    help="spine within --module (default: the module's default)")
    ap.add_argument("--time-range", default=None,
                    help="last_N_weeks | YYYY-MM-DD:YYYY-MM-DD (default: the spec's lookback)")
    ap.add_argument("--today", default=None,
                    help="ISO date override (fixtures: 2026-08-17)")
    ap.add_argument("--include-legacy", action="store_true",
                    help="include the spine's declared legacy cohort")
    ap.add_argument("--percentile", type=float, default=99.0,
                    help="settle percentile a proposed lag covers (default: 99)")
    ap.add_argument("--min-cohort-age-days", type=int, default=60,
                    help="only cohorts at least this old feed the curve (truncation guard)")
    ap.add_argument("--write", default=None, metavar="SPEC_PATH",
                    help="rewrite the stage_maturity block in this spec file in place")
    ap.add_argument("--engine", default=None, help="override KATTFOT_ENGINE (sqlite | bigquery)")
    ap.add_argument("--output-format", default="json", choices=["json"])
    args = ap.parse_args()

    spec = spine.load_spec(module=args.module, spine=args.spine)
    today = dt.date.fromisoformat(args.today) if args.today else dt.date.today()
    start, end = spine.parse_time_range(spec, args.time_range, today)
    settled_through = spine.maturity_cutoff_monday(today, args.min_cohort_age_days)

    anchor, cols = settle_columns(spec)
    where, params = spine.build_where(
        spec, {}, start, end, maturity_mode="off", include_legacy=args.include_legacy
    )
    params["settled_through"] = settled_through

    current_lags = spine.stage_maturity_table(spec).get("lag_days") or {}
    results: dict = {}
    sqls: dict = {}
    for stage, col in cols.items():
        sql = settle_sql(spec, col, anchor, where, engine=args.engine)
        rows = spine.run_query(spec["source_project"], sql, params, engine=args.engine)
        results[stage] = measure_stage(rows, args.percentile, current_lags.get(stage))
        results[stage]["settle_column"] = col
        sqls[stage] = sql

    override_results: dict = {}
    existing_overrides = spine.stage_maturity_table(spec).get("lag_days_overrides") or {}
    for stage, cfg in existing_overrides.items():
        col = cols.get(stage)
        if not col or not cfg.get("by"):
            continue
        override_results[stage] = measure_overrides(
            spec, stage, cfg, anchor, col, where, params, args.percentile,
            (results.get(stage) or {}).get("proposed_lag_days"), engine=args.engine,
        )

    fixture = spine.active_adapter(args.engine).fixture_backed
    proposal, carried = build_proposal(
        spec, results, override_results,
        pct=args.percentile, today=today, start=start,
        settled_through=settled_through, min_age=args.min_cohort_age_days,
        fixture=fixture,
    )
    rendered = render_block_yaml(proposal, carried)

    warnings = spine.fixture_warning(args.engine)
    if fixture:
        warnings.append(
            "FIXTURE CALIBRATION: these settle curves describe the committed "
            "fixture generator, not a business. The proposed block therefore "
            "keeps illustrative: true (basis: open_anchored_days_fixture) — the "
            "mechanism is demonstrated; the numbers are not measurements."
        )
    for stage, m in results.items():
        deep = m["pooled"].get("p99.9")
        if deep is not None and deep >= args.min_cohort_age_days - 7:
            warnings.append(
                f"TRUNCATION RISK ({stage}): the measured p99.9 settle lag "
                f"({deep}d) is within a week of --min-cohort-age-days "
                f"({args.min_cohort_age_days}d), so the age floor itself may be "
                f"cutting off the tail — the exact mis-specified-maximum-delay "
                f"failure Wolffram et al. (2023) found dominates nowcast bias. "
                f"Re-run with a larger --min-cohort-age-days."
            )
        if m["negative_lag_events"]:
            warnings.append(
                f"DATA QUALITY ({stage}): {m['negative_lag_events']} events have "
                f"a negative settle lag (arrival before the open anchor) and "
                f"were excluded from the curve."
            )
        tail = m["tail_share_beyond_current_lag"]
        if tail is not None and tail > 0.01:
            warnings.append(
                f"CURRENT LAG TOO SHORT ({stage}): {tail:.1%} of settled events "
                f"arrive later than the current lag of "
                f"{m['current_lag_days']}d — every rate read as mature for this "
                f"stage is biased low by that share."
            )
    if carried:
        warnings.append(
            "CARRIED FORWARD (no arrival timestamp on the spine): "
            + ", ".join(sorted(carried))
            + ". These lags remain hand-authored even in the proposed block."
        )

    if args.write:
        write_spec(Path(args.write), rendered)

    out = {
        "skill": "stage-timing/calibrate-maturity",
        "module": args.module or spine.DEFAULT_MODULE,
        "spine": args.spine,
        "source_view": spec["source_view"],
        "source_project": spec["source_project"],
        "generated_at": dt.datetime.now().isoformat(timespec="seconds"),
        "open_anchor_column": anchor,
        "percentile": args.percentile,
        "calibration_window": {
            "start": start.isoformat(),
            "end": end.isoformat(),
            "settled_through": settled_through.isoformat(),
            "min_cohort_age_days": args.min_cohort_age_days,
        },
        "stages": results,
        "overrides": {
            k: {kk: vv for kk, vv in v.items() if kk != "sql"}
            for k, v in override_results.items()
        },
        "proposed_stage_maturity": proposal,
        "proposed_block_yaml": rendered,
        "written_to": args.write,
        "sql": sqls,
        "warnings": warnings,
    }
    out.update(spine.fixture_provenance(args.engine))
    json.dump(out, sys.stdout, indent=2, default=str)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
