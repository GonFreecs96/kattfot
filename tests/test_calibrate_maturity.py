def test_write_replaces_exactly_the_marker_block(tmp_path, monkeypatch, capsys):
    target = tmp_path / "spec.yaml"
    target.write_text(SPEC_PATH.read_text())
    out = run(ARGS + ["--write", str(target)], monkeypatch, capsys)

    text = target.read_text()
    assert text.count(cm.MARKER_OPEN) == 1 and text.count(cm.MARKER_CLOSE) == 1
    rewritten = yaml.safe_load(text)
    block = rewritten["stage_maturity"]
    assert block["calibrated_at"] == TODAY
    assert block["basis"] == "open_anchored_days_fixture"
    assert block["illustrative"] is True
    assert block["lag_days"] == out["proposed_stage_maturity"]["lag_days"]
    # Everything OUTSIDE the markers survived byte-for-byte in spirit: the
    # ladder, transitions, and allow-lists still parse to the same values.
    original = yaml.safe_load(SPEC_PATH.read_text())
    for key in ("stages", "transitions", "allowed_dimensions", "terminal_branches"):
        assert rewritten[key] == original[key]


def test_write_refuses_without_markers(tmp_path, monkeypatch, capsys):
    target = tmp_path / "spec.yaml"
    target.write_text("stage_maturity:\n  lag_days: {}\n")
    monkeypatch.setattr(
        sys, "argv", ["calibrate_maturity"] + ARGS + ["--write", str(target)]
    )
    with pytest.raises(SystemExit):
        cm.main()


def test_written_block_round_trips_through_the_spine_reader(
    tmp_path, monkeypatch, capsys
):
    """The rewritten spec must still serve the per-stage machinery: cutoffs
    resolve for every ladder stage from the calibrated lags."""
    from _shared import spine

    target = tmp_path / "spec.yaml"
    target.write_text(SPEC_PATH.read_text())
    run(ARGS + ["--write", str(target)], monkeypatch, capsys)

    spec = yaml.safe_load(target.read_text())
    today = dt.date.fromisoformat(TODAY)
    cutoffs, params, meta = spine.resolve_stage_cutoffs(
        spec, spec["stages"], today, mode="stage"
    )
    assert all(c is not None for c in cutoffs.values())
    assert meta["calibrated_at"] == TODAY
