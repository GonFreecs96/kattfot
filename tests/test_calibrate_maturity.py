"""The maturity calibrator: settle curves measured, lags proposed, honesty kept.

`calibrate_maturity.py` is the generator the funnel spec's own comment block
promises ("in a real deployment this block is GENERATED by measuring
open-anchored settle time on the spine"). These tests pin four things:

1. **The arithmetic.** Nearest-rank percentiles over a histogram, and the
   tail-share computation — the number that says "your current lag silently
   drops this share of events." Both are small and easy to get off by one, and
   an off-by-one here moves every proposed lag.
2. **The end-to-end run against the committed fixtures.** Every measurable
   stage produces a curve; the proposal covers every existing lag key; the
   keys with no arrival timestamp are carried forward and *labeled*.
3. **The epistemic flags.** A fixture-backed calibration must keep
   `illustrative: true` with `basis: open_anchored_days_fixture` — measuring a
   seeded generator demonstrates the mechanism and must not produce a spec
   that claims a measured business (the same discipline test_maturity.py pins
   on the shipped spec itself).
4. **The spec rewrite.** `--write` replaces exactly the marker-delimited
   block, the result stays parseable YAML, and a file without markers refuses
   rather than guessing.

Offline throughout — sqlite adapter over the committed spine.
"""

import datetime as dt
import json
import sys
from pathlib import Path

import pytest
import yaml

import calibrate_maturity as cm

ROOT = Path(__file__).resolve().parents[1]
SPEC_PATH = ROOT / "plugins" / "assay" / "config" / "checkout-funnel-spec.yaml"

TODAY = "2026-08-17"
ARGS = ["--today", TODAY, "--time-range", "last_19_weeks"]


def run(argv, monkeypatch, capsys) -> dict:
    monkeypatch.setattr(sys, "argv", ["calibrate_maturity"] + argv)
    cm.main()
    return json.loads(capsys.readouterr().out)


# ---------------------------------------------------------------------------
# 1. Arithmetic
# ---------------------------------------------------------------------------


def test_nearest_rank_is_exact():
    hist = {0: 90, 5: 9, 30: 1}  # 100 events
    assert cm.nearest_rank(hist, 50.0) == 0
    assert cm.nearest_rank(hist, 95.0) == 5
    assert cm.nearest_rank(hist, 99.0) == 5
    assert cm.nearest_rank(hist, 99.9) == 30
    assert cm.nearest_rank(hist, 100.0) == 30
    assert cm.nearest_rank({}, 95.0) is None


def test_nearest_rank_boundary_is_inclusive():
    """p90 of ten events must land on the 9th ranked value, not the 10th —
    ceil(0.9*10)=9. A floor here would overshoot every proposal by one bin."""
    hist = {1: 9, 100: 1}
    assert cm.nearest_rank(hist, 90.0) == 1


def test_tail_share_counts_strictly_later_arrivals():
    hist = {0: 90, 5: 9, 30: 1}
    assert cm.tail_share(hist, 5) == pytest.approx(0.01)
    assert cm.tail_share(hist, 30) == 0.0
    assert cm.tail_share(hist, None) is None
    assert cm.tail_share({}, 5) is None


def test_measure_stage_excludes_negative_lags_but_reports_them():
    rows = [
        {"cohort_week": "2026-04-06", "lag_days": -1, "n": 3},
        {"cohort_week": "2026-04-06", "lag_days": 0, "n": 97},
    ]
    m = cm.measure_stage(rows, 99.0, current_lag=0)
    assert m["events"] == 97
    assert m["negative_lag_events"] == 3
    assert m["proposed_lag_days"] == 0


