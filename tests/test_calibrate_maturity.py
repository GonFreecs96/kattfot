def test_calibration_measures_every_stage_with_a_timestamp(monkeypatch, capsys):
    out = run(ARGS, monkeypatch, capsys)
    stages = out["stages"]
    for key in (
        "checkout_started", "payment_submitted", "payment_decisioned",
        "order_confirmed", "shipped", "delivered", "return_window_complete",
    ):
        m = stages[key]
        assert m["events"] > 0, key
        assert m["cohorts_used"] > 0, key
        assert m["proposed_lag_days"] is not None, key
    # Settle curves must deepen down the ladder: the return window cannot
    # settle faster than delivery, nor delivery faster than shipping.
    assert (
        stages["return_window_complete"]["proposed_lag_days"]
        > stages["delivered"]["proposed_lag_days"]
        > stages["shipped"]["proposed_lag_days"]
    )


def test_proposal_covers_every_existing_lag_key_and_labels_the_carried(
    monkeypatch, capsys
):
    spec = yaml.safe_load(SPEC_PATH.read_text())
    out = run(ARGS, monkeypatch, capsys)
    proposed = out["proposed_stage_maturity"]["lag_days"]
    for key in spec["stage_maturity"]["lag_days"]:
        assert key in proposed, key
    # Terminal-branch pseudo-stages have no arrival timestamp: carried forward
    # unchanged, and the output says which.
    carried_warning = [w for w in out["warnings"] if "CARRIED FORWARD" in w]
    assert carried_warning and "payment_declined" in carried_warning[0]
    assert (
        proposed["payment_declined"]
        == spec["stage_maturity"]["lag_days"]["payment_declined"]
    )


def test_fixture_calibration_keeps_the_illustrative_flag(monkeypatch, capsys):
    """The epistemic core: a curve measured from a seeded generator must not
    produce a spec block claiming a measured business."""
    out = run(ARGS, monkeypatch, capsys)
    block = out["proposed_stage_maturity"]
    assert block["illustrative"] is True
    assert block["basis"] == "open_anchored_days_fixture"
    assert block["calibrated_at"] == TODAY
    assert any("FIXTURE CALIBRATION" in w for w in out["warnings"])


def test_overrides_are_recalibrated_additively(monkeypatch, capsys):
    """A group earns an override only when its own settle lag exceeds the
    book-wide proposal — the additive rule the spec documents. On the fixtures
    the slow group is the bank-transfer clearing path; the instant methods
    must NOT acquire overrides."""
    out = run(ARGS, monkeypatch, capsys)
    o = out["overrides"]["payment_decisioned"]
    assert o["by"] == "payment_method"
    assert "bank_transfer_review" in o["proposed"]
    assert "card_instant" not in o["proposed"]
    book = out["stages"]["payment_decisioned"]["proposed_lag_days"]
    assert o["proposed"]["bank_transfer_review"] > book


def test_too_short_current_lags_are_called_out(monkeypatch, capsys):
    """The fixture book's hand-authored lags leave >1% of events beyond the
    cutoff for at least one stage; the calibrator must say so — this warning
    class is the whole reason to measure (mis-specified maximum delays being
    the field's top measured bias driver)."""
    out = run(ARGS, monkeypatch, capsys)
    assert any("CURRENT LAG TOO SHORT" in w for w in out["warnings"])


def test_truncation_guard_fires_when_the_age_floor_is_too_low(monkeypatch, capsys):
    """With a 45-day age floor, the ~51-day return-window tail is within a week
    of the floor — the exact configuration where the floor censors the tail,
    so the guard must fire."""
    out = run(ARGS + ["--min-cohort-age-days", "52"], monkeypatch, capsys)
    assert any(
        "TRUNCATION RISK (return_window_complete)" in w for w in out["warnings"]
    )


