def test_settle_columns_come_from_transitions_and_stage_overrides():
    spec = yaml.safe_load(SPEC_PATH.read_text())
    anchor, cols = cm.settle_columns(spec)
    assert anchor == "cart_created_at"
    # Transition arrivals.
    assert cols["checkout_started"] == "checkout_started_at"
    assert cols["return_window_complete"] == "return_window_ends_at"
    # A stage no transition arrives at, measurable via its own settle_column.
    assert cols["order_confirmed"] == "order_confirmed_at"


def test_a_spec_without_transitions_refuses():
    with pytest.raises(SystemExit):
        cm.settle_columns({"stages": [], "source_view": "v"})


